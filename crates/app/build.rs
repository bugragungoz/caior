//! 1. Generates `theme.slint` from the Bugra design tokens (design/bugra/tokens.json)
//!    into OUT_DIR, so `.slint` files never carry hand-written colors or sizes.
//! 2. Compiles the UI with the Turkish translation bundled.

use std::fmt::Write as _;
use std::path::PathBuf;

use serde_json::Value;

fn root() -> PathBuf {
    PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap()).join("../..")
}

/// "#rgb", "#rrggbb", "#rrggbbaa" or "rgba(r, g, b, a)" -> "#rrggbbaa".
fn color(value: &str) -> String {
    let v = value.trim();
    if let Some(hex) = v.strip_prefix('#') {
        return match hex.len() {
            3 => {
                let h: String = hex.chars().flat_map(|c| [c, c]).collect();
                format!("#{h}ff")
            }
            6 => format!("#{hex}ff"),
            8 => format!("#{hex}"),
            _ => panic!("bad hex color {v}"),
        };
    }
    let inner = v
        .strip_prefix("rgba(")
        .or_else(|| v.strip_prefix("rgb("))
        .and_then(|s| s.strip_suffix(')'))
        .unwrap_or_else(|| panic!("unsupported color {v}"));
    let parts: Vec<f64> = inner.split(',').map(|p| p.trim().parse().unwrap()).collect();
    let a = parts.get(3).copied().unwrap_or(1.0);
    format!(
        "#{:02x}{:02x}{:02x}{:02x}",
        parts[0] as u8,
        parts[1] as u8,
        parts[2] as u8,
        (a * 255.0).round() as u8
    )
}

fn theme_value<'a>(v: &'a Value, theme: &str) -> &'a str {
    match v {
        Value::String(s) => s,
        Value::Object(m) => m
            .get(theme)
            .or_else(|| m.get("dark"))
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("no {theme} value in {v}")),
        _ => panic!("bad token value {v}"),
    }
}

fn length(v: &str) -> String {
    let v = v.trim();
    if v.ends_with("px") || v.ends_with('%') {
        v.to_string()
    } else {
        format!("{v}px")
    }
}

fn generate_theme(tokens: &Value) -> String {
    let mut out = String::from(
        "// Generated by crates/app/build.rs from design/bugra/tokens.json. Do not edit.\n\nexport global Theme {\n    in-out property <bool> dark: true;\n",
    );

    // Colors: resolve "{alias}" against the same theme.
    let colors = tokens["color"]["tokens"].as_array().unwrap();
    let find = |name: &str, theme: &str| -> String {
        let mut current = name.to_string();
        for _ in 0..8 {
            let t = colors.iter().find(|t| t["name"] == current.as_str()).unwrap_or_else(|| panic!("unknown color {current}"));
            let raw = theme_value(&t["value"], theme);
            match raw.strip_prefix('{').and_then(|r| r.strip_suffix('}')) {
                Some(alias) => current = alias.to_string(),
                None => return color(raw),
            }
        }
        panic!("alias loop at {name}");
    };
    for t in colors {
        let name = t["name"].as_str().unwrap();
        let (d, l) = (find(name, "dark"), find(name, "light"));
        writeln!(out, "    out property <color> {name}: dark ? {d} : {l};").unwrap();
    }

    for family in ["spacing", "radius", "size"] {
        for t in tokens[family]["tokens"].as_array().unwrap() {
            let name = t["name"].as_str().unwrap();
            writeln!(out, "    out property <length> {name}: {};", length(t["value"].as_str().unwrap())).unwrap();
        }
    }
    for t in tokens["opacity"]["tokens"].as_array().unwrap() {
        writeln!(out, "    out property <float> {}: {};", t["name"].as_str().unwrap(), t["value"].as_str().unwrap()).unwrap();
    }
    for t in tokens["duration"]["tokens"].as_array().unwrap() {
        writeln!(out, "    out property <duration> {}: {};", t["name"].as_str().unwrap(), t["value"].as_str().unwrap()).unwrap();
    }
    // Shadows "x y blur color" -> <name>-y, <name>-blur, <name>-color.
    for t in tokens["shadow"]["tokens"].as_array().unwrap() {
        let name = t["name"].as_str().unwrap();
        let parse = |theme: &str| {
            let s = theme_value(&t["value"], theme);
            let cut = s.find("rgba").unwrap();
            let dims: Vec<&str> = s[..cut].split_whitespace().collect();
            (length(dims[1]), length(dims[2]), color(&s[cut..]))
        };
        let (dy, dblur, dc) = parse("dark");
        let (_, _, lc) = parse("light");
        writeln!(out, "    out property <length> {name}-y: {dy};\n    out property <length> {name}-blur: {dblur};").unwrap();
        writeln!(out, "    out property <color> {name}-color: dark ? {dc} : {lc};").unwrap();
    }

    // Type: families and styles (size, weight, letter spacing).
    let family = |key: &str| -> String {
        let f = tokens["type"]["families"][key].as_str().unwrap();
        f.split(',').next().unwrap().trim().trim_matches('"').to_string()
    };
    writeln!(out, "    out property <string> font-ui: \"{}\";", family("ui")).unwrap();
    writeln!(out, "    out property <string> font-mono: \"{}\";", family("mono")).unwrap();
    for group in tokens["type"]["groups"].as_array().unwrap() {
        if group["family"] == "og" {
            continue;
        }
        for st in group["styles"].as_array().unwrap() {
            let name = st["name"].as_str().unwrap();
            let size: f64 = st["fontSize"].as_str().unwrap().trim_end_matches("px").parse().unwrap();
            let weight = st["fontWeight"].as_i64().unwrap();
            let spacing = st["letterSpacing"]
                .as_str()
                .and_then(|s| s.strip_suffix("em"))
                .map(|em| em.parse::<f64>().unwrap() * size)
                .unwrap_or(0.0);
            writeln!(
                out,
                "    out property <length> type-{name}-size: {size}px;\n    out property <int> type-{name}-weight: {weight};\n    out property <length> type-{name}-spacing: {spacing:.2}px;"
            )
            .unwrap();
        }
    }
    out.push_str("}\n");
    out
}

fn main() {
    let tokens_path = root().join("design/bugra/tokens.json");
    println!("cargo:rerun-if-changed={}", tokens_path.display());
    let tokens: Value = serde_json::from_str(&std::fs::read_to_string(&tokens_path).unwrap()).unwrap();
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    std::fs::write(out_dir.join("theme.slint"), generate_theme(&tokens)).unwrap();

    let config = slint_build::CompilerConfiguration::new()
        .with_include_paths(vec![out_dir])
        .with_bundled_translations(root().join("i18n"))
        .with_default_translation_context(slint_build::DefaultTranslationContext::None);
    slint_build::compile_with_config(root().join("ui/app.slint"), config).unwrap();
}
